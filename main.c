// ????????????????????????????????????????????????????????????????
//  MODO MANUAL
//  Los potenciómetros controlan los servos en tiempo real.
//  'G' guarda la posición actual, 'S' regresa al menú.
// ????????????????????????????????????????????????????????????????

static void modo_manual(void)
{
	actualizar_led(MODO_MANUAL);
	uart_print("\r\nModo Manual activo.\r\n");
	uart_print("G = guardar posicion | S = salir\r\n");

	for (;;)
	{
		pos_s0 = adc_a_us(leer_adc_promedio(0));
		pos_s1 = adc_a_us(leer_adc_promedio(1));
		pos_s2 = adc_a_t2(leer_adc_promedio(2));
		pos_s3 = adc_a_t2(leer_adc_promedio(3));

		mover_servos_us(pos_s0, pos_s1, pos_s2, pos_s3);

		if (uart_disponible())
		{
			char c = uart_recibir_char();

			if (c == 'G' || c == 'g')
			{
				uart_print("\r\nIndice para guardar (0-19): ");
				uint8_t idx = (uint8_t)uart_leer_numero();
				uart_print("\r\n");

				if (idx >= MAX_FRAMES)
				{
					uart_print("Indice invalido.\r\n");
				}
				else
				{
					guardar_frame(idx, pos_s0, pos_s1, pos_s2, pos_s3);
					uart_print("Guardado en indice ");
					uart_print_num(idx);
					uart_print(".\r\n");
				}
			}
			else if (c == 'S' || c == 's')
			{
				uart_print("\r\nSaliendo de Modo Manual.\r\n");
				return;
			}
		}

		_delay_ms(20);
	}
}

// ????????????????????????????????????????????????????????????????
//  MODO EEPROM
//  Guarda o reproduce posiciones almacenadas en la EEPROM.
// ????????????????????????????????????????????????????????????????

static void modo_eeprom(void)
{
	actualizar_led(MODO_EEPROM);

	for (;;)
	{
		uart_print("\r\n===== MODO EEPROM =====\r\n");
		uart_print("1. Guardar posicion actual\r\n");
		uart_print("2. Reproducir posicion guardada\r\n");
		uart_print("S. Salir\r\n");
		uart_print("Opcion: ");

		char opcion = uart_recibir_char();
		uart_enviar_char(opcion);
		uart_print("\r\n");

		if (opcion == '1')
		{
			uart_print("Indice para guardar (0-19): ");
			uint8_t idx = (uint8_t)uart_leer_numero();
			uart_print("\r\n");

			if (idx >= MAX_FRAMES)
			{
				uart_print("Indice invalido.\r\n");
			}
			else
			{
				guardar_frame(idx, pos_s0, pos_s1, pos_s2, pos_s3);
				uart_print("Guardado en indice ");
				uart_print_num(idx);
				uart_print(".\r\n");
			}
		}
		else if (opcion == '2')
		{
			uart_print("Indice a reproducir (0-19): ");
			uint8_t idx = (uint8_t)uart_leer_numero();
			uart_print("\r\n");

			if (idx >= MAX_FRAMES)
			{
				uart_print("Indice invalido.\r\n");
			}
			else
			{
				leer_frame(idx, &pos_s0, &pos_s1, &pos_s2, &pos_s3);
				mover_servos_us(pos_s0, pos_s1, pos_s2, pos_s3);
				uart_print("Reproduciendo indice ");
				uart_print_num(idx);
				uart_print(".\r\n");
			}
		}
		else if (opcion == 'S' || opcion == 's')
		{
			uart_print("Saliendo de Modo EEPROM.\r\n");
			return;
		}
		else
		{
			uart_print("Opcion no valida.\r\n");
		}
	}
}

// ????????????????????????????????????????????????????????????????
//  MODO UART / ADAFRUIT
//  Recibe comandos en formato: M g0 g1 g2 g3# o G idx#
// ????????????????????????????????????????????????????????????????

static void modo_uart(void)
{
	char    buffer[UART_BUFFER_SIZE];
	uint8_t i = 0;

	actualizar_led(MODO_UART);

	uart_print("\r\nModo UART / Adafruit\r\n");
	uart_print("M 90 45 120 180# -> mover servos en grados\r\n");
	uart_print("G 0#             -> guardar posicion en indice 0\r\n");
	uart_print("S                -> salir\r\n");
	uart_print("\r\nUART> ");

	for (;;)
	{
		if (!uart_disponible()) continue;

		char c = uart_recibir_char();

		if (c == 'S' || c == 's')
		{
			uart_print("\r\nSaliendo de Modo UART.\r\n");
			return;
		}

		if (c == '\r' || c == '\n') continue;

		// Backspace
		if (c == 8 || c == 127)
		{
			if (i > 0) { i--; uart_print("\b \b"); }
			continue;
		}

		// Fin de comando
		if (c == '#')
		{
			buffer[i] = '\0';
			uart_print("#\r\n");
			if (i > 0) procesar_comando(buffer);
			i = 0;
			uart_print("\r\nUART> ");
			continue;
		}

		// Acumular carácter
		if (i < UART_BUFFER_SIZE - 1)
		{
			buffer[i++] = c;
			uart_enviar_char(c);
		}
		else
		{
			i = 0;
			uart_print("\r\nBuffer lleno. Intente de nuevo.\r\n");
			uart_print("\r\nUART> ");
		}
	}
}

// ????????????????????????????????????????????????????????????????
//  PROCESAR COMANDO SERIAL
// ????????????????????????????????????????????????????????????????

static void procesar_comando(char *linea)
{
	uint16_t vals[4];

	if (linea[0] == 'M' || linea[0] == 'm')
	{
		if (!extraer_numeros(linea, vals, 4))
		{
			uart_print("Formato invalido. Use: M 90 45 120 180#\r\n");
			return;
		}

		mover_servos_grados(vals[0], vals[1], vals[2], vals[3]);
		uart_print("Movimiento: ");
		for (uint8_t i = 0; i < 4; i++)
		{
			uart_print_num(vals[i]);
			if (i < 3) uart_print(" ");
		}
		uart_print("\r\n");
	}
	else if (linea[0] == 'G' || linea[0] == 'g')
	{
		if (!extraer_numeros(linea, vals, 1))
		{
			uart_print("Formato invalido. Use: G 0#\r\n");
			return;
		}

		if (vals[0] >= MAX_FRAMES)
		{
			uart_print("Indice invalido.\r\n");
			return;
		}

		guardar_frame((uint8_t)vals[0], pos_s0, pos_s1, pos_s2, pos_s3);
		uart_print("Guardado en indice ");
		uart_print_num(vals[0]);
		uart_print(".\r\n");
	}
	else
	{
		uart_print("Comando no reconocido.\r\n");
	}
}

// ????????????????????????????????????????????????????????????????
//  EXTRAER NÚMEROS DE UNA CADENA
//  Devuelve 1 si encontró exactamente 'cantidad' números, 0 si no.
// ????????????????????????????????????????????????????????????????

static uint8_t extraer_numeros(char *linea, uint16_t valores[],
uint8_t cantidad)
{
	uint8_t encontrados = 0;

	while (*linea && encontrados < cantidad)
	{
		// Avanzar hasta el próximo dígito
		while (*linea && (*linea < '0' || *linea > '9')) linea++;
		if (!*linea) break;

		// Leer número completo
		uint16_t num = 0;
		while (*linea >= '0' && *linea <= '9')
		num = num * 10 + (*linea++ - '0');

		valores[encontrados++] = num;
	}

	return (encontrados == cantidad) ? 1 : 0;
}

