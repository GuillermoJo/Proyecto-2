static uint16_t pos_s0 = SERVO_US_CENTRO;   // D9  (Timer1, µs)
static uint16_t pos_s1 = SERVO_US_CENTRO;   // D10 (Timer1, µs)
static uint16_t pos_s2 = SERVO_T2_CENTRO;   // D11 (Timer2, cuentas)
static uint16_t pos_s3 = SERVO_T2_CENTRO;   // D3  (Timer2, cuentas)

