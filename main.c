int main(void)
{
	iniciar_adc();
	iniciar_uart(BAUD_9600);
	servo_timer1_init();
	servo_timer2_init();
	iniciar_led();

	mover_servos_us(pos_s0, pos_s1, pos_s2, pos_s3);

	uart_print("\r\nSistema iniciado.\r\n");
	uart_print("Brazo mecanico listo.\r\n");

	for (;;)
	{
		mostrar_menu();

		char opcion = uart_recibir_char();
		uart_enviar_char(opcion);
		uart_print("\r\n");

		switch (opcion)
		{
			case '1': modo_manual(); break;
			case '2': modo_eeprom(); break;
			case '3': modo_uart();   break;
			default:  uart_print("Opcion no valida.\r\n"); break;
		}
	}
}

