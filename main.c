// ????????????????????????????????????????????????????????????????

// Aplica los valores directamente a los timers
static void mover_servos_us(uint16_t s0, uint16_t s1,
uint16_t s2, uint16_t s3)
{
	servo_timer1_set_us(0, s0);        // D9
	servo_timer1_set_us(1, s1);        // D10
	servo_timer2_set(0, (uint8_t)s2); // D11
	servo_timer2_set(1, (uint8_t)s3); // D3
}

// Convierte grados a unidades de cada timer y mueve los servos
static void mover_servos_grados(uint16_t g0, uint16_t g1,
uint16_t g2, uint16_t g3)
{
	if (g0 > SERVO_ANGULO_MAX) g0 = SERVO_ANGULO_MAX;
	if (g1 > SERVO_ANGULO_MAX) g1 = SERVO_ANGULO_MAX;
	if (g2 > SERVO_ANGULO_MAX) g2 = SERVO_ANGULO_MAX;
	if (g3 > SERVO_ANGULO_MAX) g3 = SERVO_ANGULO_MAX;

	pos_s0 = grados_a_us(g0);
	pos_s1 = grados_a_us(g1);
	pos_s2 = grados_a_t2(g2);
	pos_s3 = grados_a_t2(g3);

	mover_servos_us(pos_s0, pos_s1, pos_s2, pos_s3);
}

// ????????????????????????????????????????????????????????????????
//  EEPROM
//  Cada frame ocupa FRAME_SIZE bytes: 4 × uint16_t
// ????????????????????????????????????????????????????????????????

static void guardar_frame(uint8_t idx, uint16_t s0, uint16_t s1,
uint16_t s2, uint16_t s3)
{
	if (idx >= MAX_FRAMES) return;

	uint16_t base = EEPROM_BASE + (idx * FRAME_SIZE);
	eeprom_update_word((uint16_t *)(base + 0), s0);
	eeprom_update_word((uint16_t *)(base + 2), s1);
	eeprom_update_word((uint16_t *)(base + 4), s2);
	eeprom_update_word((uint16_t *)(base + 6), s3);
}

static void leer_frame(uint8_t idx, uint16_t *s0, uint16_t *s1,
uint16_t *s2, uint16_t *s3)
{
	if (idx >= MAX_FRAMES) return;

	uint16_t base = EEPROM_BASE + (idx * FRAME_SIZE);
	*s0 = eeprom_read_word((uint16_t *)(base + 0));
	*s1 = eeprom_read_word((uint16_t *)(base + 2));
	*s2 = eeprom_read_word((uint16_t *)(base + 4));
	*s3 = eeprom_read_word((uint16_t *)(base + 6));
}

// ????????????????????????????????????????????????????????????????
//  ADC
// ????????????????????????????????????????????????????????????????

// AVcc como referencia, prescaler /128 ? 125 kHz @ 16 MHz
static void iniciar_adc(void)
{
	ADMUX  = (1 << REFS0);
	ADCSRA = (1 << ADEN) | (1 << ADPS2) | (1 << ADPS1) | (1 << ADPS0);
}

// Selecciona canal, espera conversión y devuelve resultado de 10 bits
static uint16_t leer_adc(uint8_t canal)
{
	ADMUX = (ADMUX & 0xF0) | (canal & 0x07) | (1 << REFS0);
	ADCSRA |= (1 << ADSC);
	while (ADCSRA & (1 << ADSC));
	return ADC;
}

// Promedia ADC_MUESTRAS lecturas para reducir ruido
static uint16_t leer_adc_promedio(uint8_t canal)
{
	uint32_t suma = 0;
	for (uint8_t i = 0; i < ADC_MUESTRAS; i++)
	{
		suma += leer_adc(canal);
		_delay_ms(ADC_RETARDO_MS);
	}
	return (uint16_t)(suma / ADC_MUESTRAS);
}

// ????????????????????????????????????????????????????????????????
//  CONVERSIONES  —  fórmula: min + (entrada × rango) / escala
// ????????????????????????????????????????????????????????????????

// ADC (0-1023) ? pulso Timer1 (500-2500 µs)
static uint16_t adc_a_us(uint16_t adc)
{
	return (uint16_t)(SERVO_US_MIN +
	((uint32_t)adc * SERVO_US_RANGO) / ADC_MAX);
}

// ADC (0-1023) ? cuentas Timer2 (16-31)
static uint8_t adc_a_t2(uint16_t adc)
{
	return (uint8_t)(SERVO_T2_MIN +
	((uint32_t)adc * SERVO_T2_RANGO) / ADC_MAX);
}

// Grados (0-180) ? pulso Timer1 (500-2500 µs)
static uint16_t grados_a_us(uint16_t grados)
{
	if (grados > SERVO_ANGULO_MAX) grados = SERVO_ANGULO_MAX;
	return (uint16_t)(SERVO_US_MIN +
	((uint32_t)grados * SERVO_US_RANGO) / SERVO_ANGULO_MAX);
}

// Grados (0-180) ? cuentas Timer2 (16-31)
static uint8_t grados_a_t2(uint16_t grados)
{
	if (grados > SERVO_ANGULO_MAX) grados = SERVO_ANGULO_MAX;
	return (uint8_t)(SERVO_T2_MIN +
	((uint32_t)grados * SERVO_T2_RANGO) / SERVO_ANGULO_MAX);
}

// ????????????????????????????????????????????????????????????????
//  UART
// ????????????????????????????????????????????????????????????????

// 8N1, velocidad definida por UBRR
static void iniciar_uart(uint16_t ubrr)
{
	UBRR0H = (uint8_t)(ubrr >> 8);
	UBRR0L = (uint8_t)(ubrr);
	UCSR0B = (1 << RXEN0) | (1 << TXEN0);
	UCSR0C = (1 << UCSZ01) | (1 << UCSZ00);
}

// Espera buffer libre y transmite un carácter
static void uart_enviar_char(char dato)
{
	while (!(UCSR0A & (1 << UDRE0)));
	UDR0 = dato;
}

// Bloquea hasta recibir un carácter
static char uart_recibir_char(void)
{
	while (!(UCSR0A & (1 << RXC0)));
	return UDR0;
}

// Devuelve 1 si hay un carácter disponible sin bloquear
static uint8_t uart_disponible(void)
{
	return (UCSR0A & (1 << RXC0)) ? 1 : 0;
}

// Envía una cadena terminada en '\0'
static void uart_print(const char *txt)
{
	while (*txt) uart_enviar_char(*txt++);
}

// Convierte un entero sin signo a texto y lo envía
static void uart_print_num(uint16_t numero)
{
	if (numero == 0) { uart_enviar_char('0'); return; }

	char    buffer[6];
	uint8_t i = 0;

	while (numero > 0)
	{
		buffer[i++] = (numero % 10) + '0';
		numero /= 10;
	}

	while (i > 0) uart_enviar_char(buffer[--i]);
}

// Lee dígitos de la UART hasta recibir un no-dígito y devuelve el número
static uint16_t uart_leer_numero(void)
{
	uint16_t numero = 0;
	char c;

	// Descartar espacios y saltos de línea iniciales
	do { c = uart_recibir_char(); }
	while (c == ' ' || c == '\r' || c == '\n');

	while (c >= '0' && c <= '9')
	{
		uart_enviar_char(c);
		numero = numero * 10 + (c - '0');
		c = uart_recibir_char();
	}

	return numero;
}

// ????????????????????????????????????????????????????????????????
//  LED INDICADOR DE MODO
//      MANUAL  ? encendido fijo
//      EEPROM  ? apagado
//      UART    ? toggle (parpadea cada vez que se llama)
// ????????????????????????????????????????????????????????????????

static void iniciar_led(void)
{
	DDRB |= (1 << PIN_LED);
}

static void actualizar_led(uint8_t modo)
{
	switch (modo)
	{
		case MODO_MANUAL: PORTB |=  (1 << PIN_LED); break;
		case MODO_EEPROM: PORTB &= ~(1 << PIN_LED); break;
		case MODO_UART:   PORTB ^=  (1 << PIN_LED); break;
		default: break;
	}
}